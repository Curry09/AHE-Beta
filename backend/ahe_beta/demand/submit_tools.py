# Spec-0027/T2: submit-tool binding—— agent natively outputs structured data via tool parameters, binding echoes parameters for driver to read.
"""Binding for the submit tool.

nexau already applies jsonschema validation via input_schema at the tool invocation layer (archs/tool/tool.py: violations throw ValueError →
executor packages is_error result back to model → next iteration retries). Thus the agent "emits compliant data", requiring no second LLM reordering/bracket scanning.

The submit tool is set as a **stop tool**: its binding's return value becomes the return of `agent.run()` (executor's
stop_tool_result → final_response). Therefore, we **echo back the validated parameters as-is** as a JSON string—— driver
calls `json.loads` on the `agent.run` return to recover `{"dispositions": [...]}`, with no side-channel.
"""

from __future__ import annotations

import json
from typing import Any


def submit_triage(*, dispositions: list | None = None, **kwargs: Any) -> str:
    """Triage closing tool: echo back the validated dispositions array (becomes the return value of agent.run()).

    dispositions are already validated by input_schema (three disposition values, P0-P3,
    canonical English field keys, no custom fields).
    Extra nexau-injected parameters (agent_state / global_storage / ctx, etc.) are absorbed by **kwargs and do not appear in the output.
    """
    return json.dumps({"dispositions": dispositions or []}, ensure_ascii=False)


def submit_rfcs(*, proposals: list | None = None, **kwargs: Any) -> str:
    """Architect closing tool: echo back the validated proposals array (becomes the return value of agent.run()).

    The active tool validates the structural-synthesis contract generated by
    synthesis_input_schema(); this binding preserves the validated payload unchanged.
    Extra nexau-injected parameters (agent_state / global_storage / ctx, etc.) are absorbed by **kwargs.
    """
    return json.dumps({"proposals": proposals or []}, ensure_ascii=False)


def submit_divergent(*, proposals: list | None = None, **kwargs: Any) -> str:
    """Divergent PM closing tool (Spec-0028): echo back validated candidate proposals (becomes the return value of agent.run()).

    The active tool validates the product-insight contract generated by pm_input_schema().
    PM and Architect artifacts have different shapes; this binding only echoes the
    validated proposals so the driver can persist them in the proposal plane.
    """
    return json.dumps({"proposals": proposals or []}, ensure_ascii=False)


def submit_admission(*, decisions: list | None = None, **kwargs: Any) -> str:
    """Delivery Router closing tool: echo back the validated OpenAgents handoff package.

    Each entry is validated by input_schema; unlisted proposals default to direct handoff by driver and cannot be rejected via omission.
    """
    return json.dumps({"decisions": decisions or []}, ensure_ascii=False)
