# Spec-0007 / 0033 / 0040/T2: dev-side commit boundary. After containers are escalated, this gate switches from whitelist to denylist.
"""harness commit boundary gate: blocks secrets and vigil runtime state, no longer locks product shape via top-level whitelist.

Spec-0040/T2: denylist only blocks secrets and vigil runtime state.

The prior whitelist (permitting only entry.py / agents / tests …) was to prevent "welding a benchmark task into harness".
After spec-0033, deliverables are locked in containers by default with zero host mounts; overfitting channels (orchestration repo / data/sessions) are no longer visible;
RFCs (docs/specs/) and structural evolution (new directories, pyproject, README) are what the delivery surface should do. The whitelist would kill these legitimate changes in CI (evidence: after rfc:agent wrote docs/, smoke failed in 3s, blocking merge).

Still blocked: real secrets (`.env` / `.env.*`, except `.env.example`) and `.openagents/` (vigil runtime state, rebuilt with container, should not enter repo). All other top-level paths are allowed. Not relying on prompt discipline; `--no-verify` can still bypass hooks; server-side fallback is in harness_template/.gitea/workflows/smoke.yml (denylist must stay in sync with this module).
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path

# Spec-0040/T2: top-level directory/file denylist (exact match on first segment). `.env` uses separate filename rules, not in this set.
DENIED_TOP: frozenset[str] = frozenset({".openagents"})


def _is_ignorable(*, path: str) -> bool:
    """Build noise (bytecode cache), not out-of-bounds and should not enter the repo—hook skips it, do not reject the entire commit for it."""
    top = path.split("/", 1)[0]
    return top == "__pycache__" or path.endswith(".pyc") or "/__pycache__/" in path


def _is_denied(*, path: str) -> bool:
    """Return whether a relative path is on the denylist.

    Spec-0040/T2: runtime state directory, or `.env` / `.env.*` secret files except `.env.example`.
    """
    top = path.split("/", 1)[0]
    if top in DENIED_TOP:
        return True
    for part in path.split("/"):
        if part == ".env.example":
            continue
        if part == ".env" or part.startswith(".env."):
            return True
    return False


def violations(staged_paths: Iterable[str]) -> list[str]:
    """Given a set of relative paths of staged files, return those that violate boundaries (secrets / vigil runtime state)."""
    bad: list[str] = []
    for raw in staged_paths:
        path = raw.strip()
        if not path or _is_ignorable(path=path):
            continue
        if _is_denied(path=path):
            bad.append(path)
    return bad


# pre-commit hook script: self-contained (depends only on python3 stdlib + git), does not import this package—harness repo is standalone,
# hook runs within it, PYTHONPATH may not include ahe_beta. Denylist is injected from this module, logic originates from violations().
_HOOK_TEMPLATE = """#!/usr/bin/env python3
# AHE-Beta harness boundary gate (generated by ahe_beta.guards.harness_boundary; do not edit).
# Reject secrets and Vigil runtime state only; allow other top-level paths, including
# docs/specs and structural evolution. Container containment replaces a path allowlist.
import subprocess
import sys

DENIED_TOP = {denied_top}


def _ignorable(path):
    top = path.split("/", 1)[0]
    return top == "__pycache__" or path.endswith(".pyc") or "/__pycache__/" in path


def _denied(path):
    top = path.split("/", 1)[0]
    if top in DENIED_TOP:
        return True
    for part in path.split("/"):
        if part == ".env.example":
            continue
        if part == ".env" or part.startswith(".env."):
            return True
    return False


staged = subprocess.run(
    ["git", "diff", "--cached", "--name-only"], capture_output=True, text=True
).stdout.split("\\n")
bad = []
for p in staged:
    path = p.strip()
    if not path or _ignorable(path) or not _denied(path):
        continue
    bad.append(path)
if bad:
    sys.stderr.write(
        "\\n[harness-boundary] Commit rejected. Only actual secrets (.env / .env.*, except "
        ".env.example) and .openagents/ (Vigil runtime state) are blocked. docs/, new "
        "directories, and product files are allowed. Remove the following files and retry: \\n  "
        + "\\n  ".join(bad)
        + "\\n"
    )
    sys.exit(1)
"""


def render_hook() -> str:
    """Render pre-commit hook script text (denylist inlined as Python set literal)."""
    return _HOOK_TEMPLATE.format(denied_top=set(DENIED_TOP))


def install_pre_commit(repo: Path) -> None:
    """Write boundary hook to `<repo>/.git/hooks/pre-commit` and make executable (overwrites old hook). Repo must be git init'd."""
    hook = Path(repo) / ".git" / "hooks" / "pre-commit"
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(render_hook(), encoding="utf-8")
    hook.chmod(0o755)
