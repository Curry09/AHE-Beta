"""git SeedSource (spec-0009/T4).

Spec-0009/T4: git source (repo@commit snapshot workspace)

provision returns a clean snapshot directory of a repository pinned to a specific commit—the
starting point for real repo tasks (SWE-bench base_commit unfixed state, funcy@some-version, etc.).
repo/commit (and optional ref/depth) are fully contained in `WorkspaceSpec.params`; schema and
kind="git" are not extended.

Network policy (survival under large repos + slow networks): cache is shared per **repository**
(backend/data/repo_cache/<slug>/repo), with each target commit fetched from the network only once—
`git fetch --depth 1 <repo> <sha>:refs/seeds/<sha>` performs targeted shallow fetch by SHA (GitHub
supports reachable SHA fetch; subsequent commits in the same repo use incremental delta, only a
few MB). When the server does not support SHA-based fetch, the backend falls back to full clone
to rebuild the cache (compatible with local bare-repository paths). Thereafter, each provision
copytrees the cache + checks out the target commit in the copy; each session remains an isolated
directory with no cross-session state pollution (isolation semantics equivalent to "fresh clone
per session").

Pluggable proof: integrating it only adds this module—auto-discovered and registered by
spec-0009/T1's sources/ mechanism; seed_source / models / workspace and the consumer side
(orchestrator / sim_user / Sandbox) remain unchanged."""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from pathlib import Path

from ahe_beta.models import WorkspaceSpec
from ahe_beta.user.sim.seed_source import register

# Repository cache root: backend/data/repo_cache (runtime artifacts, globally .gitignored under data/).
_CACHE_ROOT = Path(__file__).resolve().parents[4] / "data" / "repo_cache"


@register("git")
class GitSource:
    kind = "git"

    def provision(self, spec: WorkspaceSpec, dest_root: str | None = None) -> str:
        """Provision an isolated working tree of repo@commit (pure local copy on cache hit).

        Spec-0009/T4: read repo (required), commit (required), and optional ref/depth from spec.params;
        ensure the commit object is in the repository cache, then copytree to an isolated directory
        and checkout, returning the absolute path to that directory.
        """
        # 1. Read and self-validate params (do not expand WorkspaceSpec; field completeness guaranteed by source).
        repo = spec.params.get("repo")
        commit = spec.params.get("commit")
        if not repo:
            raise ValueError(
                "git source requires non-empty params.repo (a cloneable URL or local path)"
            )
        if not commit:
            raise ValueError(
                "git source requires non-empty params.commit (the snapshot sha/ref to restore)"
            )
        ref = spec.params.get("ref")
        depth = spec.params.get("depth")

        cache = _ensure_commit_cached(repo=str(repo), commit=str(commit), ref=ref, depth=depth)

        # 2. Fresh per session: copy an independent directory from the cache and checkout; no cross-session pollution, cleanable.
        base = dest_root or tempfile.mkdtemp(prefix="sim_ws_git_")
        dest = Path(base) / "repo"
        shutil.copytree(cache, dest, symlinks=True)

        # 3. Checkout to the target commit; shallow clone may not fetch arbitrary historical commits,
        #    fall back to fetch --unshallow for full fetch and retry (compatibility for shallow clone + arbitrary commit).
        try:
            _run_git(cmd=["git", "checkout", "-q", str(commit)], cwd=str(dest))
        except RuntimeError:
            if not depth:
                raise
            _run_git(cmd=["git", "fetch", "--unshallow"], cwd=str(dest))
            _run_git(cmd=["git", "checkout", str(commit)], cwd=str(dest))

        return str(dest.resolve())


def _ensure_commit_cached(*, repo: str, commit: str, ref: str | None, depth: int | None) -> Path:
    """Ensure the commit object is in the repository's shared cache and return the cache path;
    network access only on cache miss.

    Fetch priority: ① `fetch --depth 1 <repo> <sha>:refs/seeds/<sha>` performs targeted shallow
    fetch by SHA and anchors the object with a ref (preventing gc); incremental delta reuse for
    multiple commits in the same repo; ② on first commit, if the server rejects SHA-based fetch
    (local bare-repository path / old server), fall back to full clone to rebuild cache. After each
    commit succeeds, a marker is placed in shas/<sha>; cache hit skips network access. The cache
    itself is not checked out (copytree only moves .git; the working tree is generated by the copy
    in the provision step).
    """
    slug = re.sub(r"[^A-Za-z0-9._-]+", "-", repo).strip("-")[-60:] or "repo"
    entry = _CACHE_ROOT / slug
    cache = entry / "repo"
    markers = entry / "shas"
    marker = markers / commit
    if marker.is_file() and (cache / ".git").is_dir():
        return cache
    markers.mkdir(parents=True, exist_ok=True)
    if not (cache / ".git").is_dir():  # First creation or remnant from previous build
        shutil.rmtree(cache, ignore_errors=True)
        _run_git(cmd=["git", "init", "-q", str(cache)], cwd=None)

    # Existing objects (e.g., already retrieved via full fallback) → zero network
    if _has_commit(cache=cache, commit=commit):
        marker.touch()
        return cache

    try:
        _run_git(
            cmd=["git", "fetch", "--depth", "1", repo, f"{commit}:refs/seeds/{commit[:12]}"],
            cwd=str(cache),
        )
    except RuntimeError:
        if any(markers.iterdir()):
            # Cache has prior content, only new commit's SHA-based fetch failed → full fetch to update;
            # Reachability is ultimately diagnosed by checkout in the provision copy.
            _run_git(
                cmd=["git", "fetch", repo, "+refs/heads/*:refs/seeds/heads/*"],
                cwd=str(cache),
            )
        else:
            # Fallback: full clone (legacy path); optional depth/ref for acceleration (compatible with local repository paths / old servers).
            shutil.rmtree(cache)
            clone_cmd = ["git", "clone"]
            if depth:
                clone_cmd += ["--depth", str(depth)]
            if ref:
                clone_cmd += ["--branch", str(ref)]
            clone_cmd += [repo, str(cache)]
            _run_git(cmd=clone_cmd, cwd=None)

    marker.touch()
    return cache


def _has_commit(*, cache: Path, commit: str) -> bool:
    """Check whether the commit object already exists in the cache repository (cat-file -e;
    any failure is treated as non-existent)."""
    try:
        _run_git(cmd=["git", "cat-file", "-e", f"{commit}^{{commit}}"], cwd=str(cache))
        return True
    except RuntimeError:
        return False


def _run_git(*, cmd: list[str], cwd: str | None) -> subprocess.CompletedProcess[str]:
    """Run a git subprocess, raising with diagnostics on failure.

    Spec-0009/T4: on clone/checkout failure, raise RuntimeError with diagnostics carrying failed command + returncode + truncated stderr (aligned with T3 deps.py error style).
    """
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if proc.returncode != 0:
        stderr = (proc.stderr or "").strip()
        if len(stderr) > 2000:
            stderr = stderr[:2000] + "…(stderr truncated)"
        raise RuntimeError(
            f"git command failed: {' '.join(cmd)} (returncode={proc.returncode})\nstderr: {stderr}"
        )
    return proc
